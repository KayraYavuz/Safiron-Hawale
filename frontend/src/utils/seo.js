/**
 * Create SEO metadata for a given page and language
 * @param {string} page - Page key (e.g., 'landing', 'features', 'pricing', 'blog', 'about', 'contact')
 * @param {string} lang - Language code (e.g., 'en', 'tr', 'ar')
 * @returns {Object} SEO metadata object with title, description, keywords, og tags, etc.
 */
export function createSeoMetadata(page, lang) {
  const pageData = SEO_PAGES[lang]?.[page];

  if (!pageData) {
    throw new Error(`SEO metadata not found for page: ${page}, language: ${lang}`);
  }

  return {
    title: pageData.title,
    description: pageData.description,
    keywords: pageData.keywords,
    ogTitle: pageData.ogTitle,
    ogDescription: pageData.ogDescription,
    ogImage: pageData.ogImage,
    ogUrl: pageData.ogUrl,
    canonicalUrl: pageData.canonicalUrl,
    lang: lang,
  };
}
